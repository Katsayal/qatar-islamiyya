// One-off generator for Qur'an position data (Hafs, 604-page 15-line Madinah mushaf).
// Source: quran.com API v4 (word-level page/line numbers). No Qur'an text is stored.
//   node scripts/build-quran-data.mjs
// Writes:
//   supabase/migrations/20261008234915_quran_ayahs_data.sql  (6,236 rows)
//   src/lib/surahs.ts                                       (114 surah names + ayah counts)
import { writeFileSync } from "node:fs";

const API = "https://api.quran.com/api/v4";
const DATA_MIGRATION = "supabase/migrations/20261008234915_quran_ayahs_data.sql";
const SURAHS_FILE = "src/lib/surahs.ts";

async function get(path) {
  for (let attempt = 1; attempt <= 3; attempt++) {
    const res = await fetch(API + path);
    if (res.ok) return res.json();
    console.warn(`retry ${attempt} ${path} (${res.status})`);
    await new Promise((r) => setTimeout(r, 1000 * attempt));
  }
  throw new Error(`Failed: ${path}`);
}

// --- Surahs ---
const { chapters } = await get("/chapters");
const surahs = chapters.map((c) => ({
  number: c.id,
  name: c.name_simple,
  nameAr: c.name_arabic,
  ayahs: c.verses_count,
}));

// --- Ayah positions, page by page ---
const rows = new Map(); // "s:a" → row
for (let page = 1; page <= 604; page++) {
  let p = 1;
  let totalPages = 1;
  do {
    const d = await get(
      `/verses/by_page/${page}?words=true&word_fields=line_number,page_number&fields=juz_number&per_page=50&page=${p}`,
    );
    totalPages = d.pagination.total_pages;
    for (const v of d.verses) {
      const [surah, ayah] = v.verse_key.split(":").map(Number);
      const first = v.words[0];
      const last = v.words[v.words.length - 1];
      rows.set(v.verse_key, {
        surah,
        ayah,
        page: first.page_number,
        line: first.line_number,
        end_page: last.page_number,
        end_line: last.line_number,
        juz: v.juz_number,
      });
    }
    p++;
  } while (p <= totalPages);
  if (page % 50 === 0) console.log(`page ${page}/604`);
}

// --- Validate before writing anything ---
const all = [...rows.values()].sort((a, b) => a.surah - b.surah || a.ayah - b.ayah);
const fail = (msg) => {
  throw new Error(`Validation failed: ${msg}`);
};
if (all.length !== 6236) fail(`expected 6236 ayahs, got ${all.length}`);
for (const s of surahs) {
  const n = all.filter((r) => r.surah === s.number).length;
  if (n !== s.ayahs) fail(`surah ${s.number}: ${n} ayahs, expected ${s.ayahs}`);
}
const pages = new Set(all.map((r) => r.page));
for (let pg = 1; pg <= 604; pg++) if (!pages.has(pg) && !all.some((r) => r.page < pg && r.end_page >= pg)) fail(`page ${pg} has no ayah`);
for (const r of all) {
  if (r.line < 1 || r.line > 15 || r.end_line < 1 || r.end_line > 15) fail(`bad line ${r.surah}:${r.ayah}`);
  if (r.end_page * 100 + r.end_line < r.page * 100 + r.line) fail(`end before start ${r.surah}:${r.ayah}`);
}
const at = (s, a) => rows.get(`${s}:${a}`);
if (at(1, 1).page !== 1) fail("1:1 should be page 1");
if (at(2, 1).page !== 2) fail("2:1 should be page 2");
if (at(18, 1).page !== 293) fail("18:1 should be page 293");
if (at(114, 6).page !== 604) fail("114:6 should be page 604");

// --- Write migration ---
const values = all.map(
  (r) => `(${r.surah},${r.ayah},${r.page},${r.line},${r.end_page},${r.end_line},${r.juz})`,
);
let sql = "-- GENERATED by scripts/build-quran-data.mjs (quran.com API v4). Do not edit by hand.\n";
sql += "-- Hafs, 604-page 15-line Madinah mushaf: start/end page+line and juz per ayah.\n";
for (let i = 0; i < values.length; i += 500) {
  sql += "insert into public.quran_ayahs (surah, ayah, page, line, end_page, end_line, juz) values\n";
  sql += values.slice(i, i + 500).join(",\n") + ";\n";
}
writeFileSync(DATA_MIGRATION, sql);

// --- Write surahs.ts ---
let ts = "// GENERATED by scripts/build-quran-data.mjs (quran.com API v4). Do not edit by hand.\n";
ts += "export type Surah = { number: number; name: string; nameAr: string; ayahs: number };\n\n";
ts += "export const surahs: Surah[] = [\n";
for (const s of surahs) ts += `  ${JSON.stringify(s)},\n`;
ts += "];\n";
writeFileSync(SURAHS_FILE, ts.replace(/"(\w+)":/g, "$1: "));

console.log(`OK: ${all.length} ayahs, ${surahs.length} surahs → ${DATA_MIGRATION}, ${SURAHS_FILE}`);
